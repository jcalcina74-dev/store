CREATE TABLE "T_Administrador" (
 id BIGINT PRIMARY KEY CHECK (id = 1),
 usuario VARCHAR(50) NOT NULL UNIQUE CHECK (TRIM(usuario) <> ''),
 password_hash VARCHAR(255) NOT NULL
);
CREATE TABLE "T_Marca" (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(80) NOT NULL CHECK (TRIM(nombre) <> ''),
 CONSTRAINT uk_marca_nombre UNIQUE(nombre)
);
CREATE TABLE "T_Celular" (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 marca_id BIGINT NOT NULL REFERENCES "T_Marca"(id) ON DELETE RESTRICT,
 modelo VARCHAR(120) NOT NULL CHECK (TRIM(modelo) <> ''),
 descripcion TEXT,
 precio NUMERIC(12,2) NOT NULL CHECK (precio > 0),
 stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
 ram_gb INTEGER NOT NULL CHECK (ram_gb > 0),
 almacenamiento_gb INTEGER NOT NULL CHECK (almacenamiento_gb > 0),
 pantalla_pulgadas NUMERIC(4,2) NOT NULL CHECK (pantalla_pulgadas > 0),
 bateria_mah INTEGER NOT NULL CHECK (bateria_mah > 0),
 sistema_operativo VARCHAR(80) NOT NULL CHECK (TRIM(sistema_operativo) <> ''),
 color VARCHAR(50) NOT NULL CHECK (TRIM(color) <> ''),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT uk_celular_variante UNIQUE(marca_id, modelo, ram_gb, almacenamiento_gb, color)
);
CREATE INDEX idx_celular_marca ON "T_Celular"(marca_id);
CREATE INDEX idx_celular_publico ON "T_Celular"(activo, id DESC);
CREATE TABLE "T_ImagenCelular" (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 celular_id BIGINT NOT NULL REFERENCES "T_Celular"(id) ON DELETE CASCADE,
 ruta_relativa VARCHAR(255) NOT NULL UNIQUE CHECK (TRIM(ruta_relativa) <> ''),
 mime_type VARCHAR(50) NOT NULL CHECK (mime_type = 'image/webp'),
 tamanio_bytes BIGINT NOT NULL CHECK (tamanio_bytes > 0),
 ancho INTEGER NOT NULL CHECK (ancho > 0),
 alto INTEGER NOT NULL CHECK (alto > 0),
 orden INTEGER NOT NULL CHECK (orden >= 0),
 CONSTRAINT uk_imagen_orden UNIQUE(celular_id, orden)
);